-- FUNCIÓN 1: LOGIN CENTRALIZADO
CREATE OR REPLACE FUNCTION fn_login_centralizado (
    p_username VARCHAR2,
    p_password_text VARCHAR2
) RETURN NUMBER IS
    PRAGMA AUTONOMOUS_TRANSACTION;
    v_stored_hash VARCHAR2(64);
    v_usuario_id NUMBER;
    v_intentos NUMBER;
BEGIN
    BEGIN
        SELECT usuario_id, password_hash, intentos_fallidos 
        INTO v_usuario_id, v_stored_hash, v_intentos
        FROM Usuario_Sistema 
        WHERE username = p_username AND estado = 1;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN RETURN 0;
    END;

    IF v_intentos >= 5 THEN
        RETURN -1; -- Cuenta Bloqueada
    END IF;
    
    IF v_stored_hash = RAWTOHEX(DBMS_CRYPTO.HASH(UTL_I18N.STRING_TO_RAW(p_password_text, 'AL32UTF8'), DBMS_CRYPTO.HASH_SH256)) THEN
        UPDATE Usuario_Sistema 
        SET ultimo_acceso = CURRENT_TIMESTAMP, 
            intentos_fallidos = 0 
        WHERE usuario_id = v_usuario_id;
        COMMIT;
        RETURN 1;
    ELSE
        UPDATE Usuario_Sistema 
        SET intentos_fallidos = intentos_fallidos + 1 
        WHERE usuario_id = v_usuario_id;
        COMMIT;
        RETURN 0;
    END IF;
END;
/

