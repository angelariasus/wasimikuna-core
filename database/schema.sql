-- PROCEDIMIENTO 2: Crear Orden de Compra
CREATE OR REPLACE PROCEDURE sp_registrar_compra_completa (
    p_afiliado_id NUMBER,
    p_usuario_creador NUMBER,
    p_fecha_entrega DATE,
    p_detalles SYS_REFCURSOR
) AS
    v_orden_id NUMBER;
    v_prod_id NUMBER;
    v_cant NUMBER;
    v_precio NUMBER;
    v_total NUMBER := 0;
BEGIN
    INSERT INTO Orden_Compra (afiliado_id, usuario_creacion_id, fecha_entrega_prevista, estado)
    VALUES (p_afiliado_id, p_usuario_creador, p_fecha_entrega, 0)
    RETURNING orden_compra_id INTO v_orden_id;

    LOOP
        FETCH p_detalles INTO v_prod_id, v_cant, v_precio;
        EXIT WHEN p_detalles%NOTFOUND;
        
        INSERT INTO Detalle_Orden (orden_compra_id, producto_id, cantidad, precio_unitario, subtotal)
        VALUES (v_orden_id, v_prod_id, v_cant, v_precio, (v_cant * v_precio));
        
        v_total := v_total + (v_cant * v_precio);
    END LOOP;
    
    UPDATE Orden_Compra SET total = v_total WHERE orden_compra_id = v_orden_id;
    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END;
/

-- PROCEDIMIENTO 3: Procesar Recepción (BLOB)
