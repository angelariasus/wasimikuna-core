BEGIN
    INSERT INTO Recepcion (
        envio_id, 
        comite_miembro_id, 
        estado_conformidad, 
        observaciones_generales, 
        acta_archivo, 
        acta_mime_type, 
        acta_nombre_archivo
    )
    VALUES (
        p_envio_id, 
        p_comite_miembro_id, 
        'CONFORME', 
        p_observaciones, 
        p_acta_blob, 
        p_acta_mime, 
        p_acta_nombre
    );
    
    UPDATE Envio SET estado_envio = 'ENTREGADO' WHERE envio_id = p_envio_id;
    COMMIT;
END;
