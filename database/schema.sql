CREATE OR REPLACE VIEW VW_KARDEX_ENTRADAS AS
SELECT 
    ie.nombre AS colegio,
    p.nombre AS producto,
    dr.lote_fabricacion,
    dr.fecha_vencimiento,
    SUM(dr.cantidad_recibida) AS total_ingresado,
    MAX(r.fecha_recepcion) AS ultima_entrada
FROM Detalle_Recepcion dr
JOIN Recepcion r ON dr.recepcion_id = r.recepcion_id
JOIN Envio e ON r.envio_id = e.envio_id
JOIN Institucion_Educativa ie ON e.institucion_id = ie.institucion_id
JOIN Producto p ON dr.producto_id = p.producto_id
WHERE r.estado_conformidad = 'CONFORME'
GROUP BY ie.nombre, p.nombre, dr.lote_fabricacion, dr.fecha_vencimiento;

CREATE OR REPLACE VIEW VW_CONSUMO_MENUS AS
SELECT 
    pm.institucion_id,
    rp.producto_id,
    SUM(pm.cantidad_raciones * rp.cantidad_por_racion) AS total_consumido
FROM Programacion_Menu pm
JOIN Receta_Producto rp ON pm.plato_id = rp.plato_id
WHERE pm.estado_preparacion = 'SERVIDO'
GROUP BY pm.institucion_id, rp.producto_id;

CREATE OR REPLACE VIEW VW_STOCK_ACTUAL AS
SELECT 
    ie.nombre AS colegio,
    p.nombre AS producto,
    NVL(SUM(dr.cantidad_recibida), 0) AS total_ingresos,
    NVL((SELECT total_consumido 
         FROM VW_CONSUMO_MENUS cm 
         WHERE cm.institucion_id = ie.institucion_id 
           AND cm.producto_id = p.producto_id), 0) AS total_salidas,
    (NVL(SUM(dr.cantidad_recibida), 0) - 
     NVL((SELECT total_consumido 
          FROM VW_CONSUMO_MENUS cm 
          WHERE cm.institucion_id = ie.institucion_id 
            AND cm.producto_id = p.producto_id), 0)) AS stock_actual
FROM Detalle_Recepcion dr
JOIN Recepcion r ON dr.recepcion_id = r.recepcion_id
JOIN Envio e ON r.envio_id = e.envio_id
JOIN Institucion_Educativa ie ON e.institucion_id = ie.institucion_id
JOIN Producto p ON dr.producto_id = p.producto_id
WHERE r.estado_conformidad = 'CONFORME'
GROUP BY ie.institucion_id, ie.nombre, p.producto_id, p.nombre;

